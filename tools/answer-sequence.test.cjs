const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync(process.argv[2]||'raw.html','utf8');
const start=html.indexOf('    const fw=s=>');
const end=html.indexOf('    async function akFromPdf(',start);
assert.ok(start>=0&&end>start);
const context=vm.createContext({});
vm.runInContext(html.slice(start,end),context);
const parse=text=>JSON.parse(JSON.stringify(context.akFromText(text)));
assert.deepEqual(parse('CAABC/DDCAD'),{1:'C',2:'A',3:'A',4:'B',5:'C',6:'D',7:'D',8:'C',9:'A',10:'D'});
assert.deepEqual(parse('ｃａａｂｃ／ｄｄｃａｄ'),parse('CAABC/DDCAD'));
assert.deepEqual(parse(' CAABC /\n DDCAD '),parse('CAABC/DDCAD'));
assert.deepEqual(parse('ABCDE/AC'),{1:'A',2:'B',3:'C',4:'D',5:'E',6:'A',7:'C'});
assert.deepEqual(parse('A'),{1:'A'});
assert.throws(()=>parse('CAAB/DDCAD'),/每 5 題/);
assert.throws(()=>parse('CAABC/'),/每 5 題/);
assert.throws(()=>parse('CAABCDDCAD'),/每 5 題/);
assert.deepEqual(parse('1.C 2.D 3.A'),{1:'C',2:'D',3:'A'});
assert.deepEqual(parse('1.AC 2.BD'),{1:'AC',2:'BD'});
assert.deepEqual(parse('1 2 3\nC D A'),{1:'C',2:'D',3:'A'});
assert.deepEqual(parse(''),{});
const paste=html.split('\n').find(line=>line.trim().startsWith('window.pasteAnswerKey=function'));
let input='CAABC/DDCAD',applied=null,error='';
context.window=context;
context.prompt=message=>{assert.match(message,/CAABC\/DDCAD/);return input};
context.applyAnswerKey=map=>{applied=JSON.parse(JSON.stringify(map))};
context.akSay=()=>{};context.alert=message=>{error=message};
vm.runInContext(paste,context);
context.pasteAnswerKey();assert.deepEqual(applied,parse(input));
input='CAAB/DDCAD';applied=null;context.pasteAnswerKey();assert.equal(applied,null);assert.match(error,/每 5 題/);
input=null;context.pasteAnswerKey();assert.equal(applied,null);
console.log('PASS: grouped answer sequence, full-width/lowercase, partial last group, invalid groups, numbered and multi-answer compatibility');
