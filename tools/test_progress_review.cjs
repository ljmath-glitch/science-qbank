const assert=require('assert');
const R=require('../progress-review.js');
const q={id:'1',year:'115',school:'甲中',exam:'115上段考',no:'2',ans:'A',book:'B1',book_name:'七上',field:'生物',unit:'C1',sub:'1-1',kp:'細胞',summary:'摘要',type:'A1',step:1,mem:1,con:1,chart:'無',basis:'依課本',flag:false,q:'題幹',sol:'詳解',group_id:'g',imgs:['https://x/a.png']};
assert.strictEqual(R.FIELD_NAMES.length,23);
const fields=R.questionFields(q,{g:'題組文章'});
assert.deepStrictEqual(Object.keys(fields),R.FIELD_NAMES);
assert.strictEqual(fields['題組文章'],'題組文章'); assert.strictEqual(fields['待確認'],'（空）');
const exported=R.buildExport('甲中考卷',[{...q,id:'2',no:'10'},{...q,id:'1',no:'2'}],{passages:{g:'文章'},exported_at:'2026-01-01T00:00:00.000Z'});
assert.deepStrictEqual(exported.questions.map(x=>x.id),['1','2']);
assert.strictEqual(exported.questions[0].images[0].name,'a.png');
assert.strictEqual(JSON.parse(JSON.stringify(exported)).questions.length,2);
const parsed=R.parseAiJson('[{"id":"1","verdict":"fix","issues":[{"field":"題目","problem":"錯字","suggest":"更正"}],"category":{"book":"B2","book_name":"八上","unit":"C2"},"difficulty":{"step":2,"mem":2,"concept":1},"confidence":"高"}]');
assert.strictEqual(parsed[0].con,1); assert.strictEqual(parsed[0].issues[0].field,'題目');
const imported=R.importAiResults(JSON.stringify(parsed),[q]);
assert.strictEqual(imported.valid,true); assert.deepStrictEqual(imported.rows[0].changes,{book:'B2',book_name:'八上',unit:'C2',step:2,mem:2});
assert.strictEqual(R.importAiResults('not json',[q]).valid,false);
assert.strictEqual(R.importAiResults('[{"id":"missing","verdict":"fix"}]',[q]).rows[0].parseable,false);
assert.deepStrictEqual(R.editablePatch(q,{id:'1',book:'B2',q:'不可寫',flag:true,step:2}),{book:'B2',step:2});
const backup=R.buildBackup('測驗',[{id:'1',before:q}]);
assert.deepStrictEqual(R.restorePatch(backup.items[0]),{book:'B1',book_name:'七上',unit:'C1',step:1,mem:1,con:1});
console.log('progress-review tests passed');
